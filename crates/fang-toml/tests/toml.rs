//! Controls of the TOML subset. The equivalence runs compare every Cargo.toml, Cargo.lock and
//! rust-toolchain.toml of the repository against tomllib.loads.
use fang_json::{ParseLimits, Value, parse as json};
use fang_toml::parse;

fn expect(toml: &str, json_text: &str) {
    let expected = json(json_text.as_bytes(), &ParseLimits::default()).unwrap();
    assert_eq!(parse(toml).unwrap(), expected, "document {toml:?}");
}

#[test]
fn manifest_shapes() {
    expect(
        concat!(
            "# comment\n",
            "[package]\n",
            "name = \"fang-hash\"  # trailing\n",
            "version.workspace = true\n",
            "edition = 'literal'\n",
            "\n",
            "[dependencies]\n",
            "fang-json = { path = \"../fang-json\" }\n",
            "other = { version = \"1\", features = [\"a\", \"b\",] }\n",
            "\n",
            "[workspace]\n",
            "members = [\n",
            "    \"crates/a\",  # one\n",
            "    \"crates/b\",\n",
            "]\n",
            "[lints.rust]\n",
            "unsafe_code = \"forbid\"\n",
        ),
        r#"{"package": {"name": "fang-hash", "version": {"workspace": true}, "edition": "literal"},
            "dependencies": {"fang-json": {"path": "../fang-json"}, "other": {"version": "1", "features": ["a", "b"]}},
            "workspace": {"members": ["crates/a", "crates/b"]},
            "lints": {"rust": {"unsafe_code": "forbid"}}}"#,
    );
}

#[test]
fn lockfile_shapes() {
    expect(
        concat!(
            "# This file is automatically @generated by Cargo.\n",
            "version = 4\n",
            "\n",
            "[[package]]\n",
            "name = \"a\"\n",
            "version = \"0.0.0\"\n",
            "dependencies = [\n",
            " \"b\",\n",
            "]\n",
            "\n",
            "[[package]]\n",
            "name = \"b\"\n",
            "version = \"0.1.0\"\n",
        ),
        r#"{"version": 4, "package": [{"name": "a", "version": "0.0.0", "dependencies": ["b"]},
            {"name": "b", "version": "0.1.0"}]}"#,
    );
}

#[test]
fn strings_integers_and_tables() {
    expect(
        concat!(
            "a = \"tab\\tquote\\\" \\u00e9 \\U0001F600\"\n",
            "b = '''\nraw \\n ''text'''''\n",
            "c = \"\"\"\nline one\\\n    continued\"\"\"\n",
            "d = [1_000, 0x1f, 0o17, 0b101, -5, +6]\n",
            "e = []\n",
            "[x.y]\n",
            "z = 1\n",
            "[x]\n",
            "w = 2\n",
            "[[t]]\n",
            "[t.inner]\n",
            "k = 1\n",
            "[[t]]\n",
            "\"quoted key\" = 3\n",
        ),
        r#"{"a": "tab\tquote\" é 😀", "b": "raw \\n ''text''", "c": "line onecontinued",
            "d": [1000, 31, 15, 5, -5, 6], "e": [],
            "x": {"y": {"z": 1}, "w": 2},
            "t": [{"inner": {"k": 1}}, {"quoted key": 3}]}"#,
    );
}

#[test]
fn tomllib_refusals() {
    for document in [
        "a = 1\na = 2\n",
        "[a]\n[a]\n",
        "[a]\nb.c = 1\n[a.b]\n",
        "a = {b = 1}\n[a]\n",
        "a = {b = 1}\na.c = 2\n",
        "a = [1]\n[[a]]\n",
        "[[a]]\n[a]\n",
        "a = 1.5\n",
        "a = 1979-05-27\n",
        "a = 012\n",
        "a = 1__0\n",
        "a = \"unterminated\n",
        "a = 1 b = 2\n",
        "a = {b = 1, b = 2}\n",
        "a = \"\\q\"\n",
    ] {
        assert!(parse(document).is_err(), "accepted {document:?}");
    }
}

#[test]
fn empty_document_is_an_empty_table() {
    assert_eq!(parse("").unwrap(), Value::Object(Default::default()));
    assert_eq!(
        parse("\n# only a comment\n\r\n").unwrap(),
        Value::Object(Default::default())
    );
}
