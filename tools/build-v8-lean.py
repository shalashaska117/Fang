#!/usr/bin/env python3
"""Build lean-v8 with Lake (fang-v8-check and fang-v8-tstp), then rerun the fixed axiom audits.

The recipe checks every lean-v8 file against tools/v8_szs/lean-sources.json,
requires the exact import closures of every executable and of the library,
checks the backend packages against tools/v8_szs/backend-pins.json before and
after the build, builds offline with Lake (no cache download, no network Git),
and audits the fixed theorems of every gate named in lean-v8/audits.json, gate
by gate: each must use only propext, Classical.choice and Quot.sound, exactly
as that gate recorded.

Backend sources: --backend copies a pinned local backend (it is never written
to); --packages uses a package directory produced by tools/fetch-v8-backend.py.
"""
# Copyright (c) 2026 Pietro Pellegrino. BSD 3-Clause license.
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

sys.dont_write_bytecode = True
TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
from fang_szs import v8_backend, v8_dependencies as sources
from fang_szs.supervisor import Limits, Supervisor, write_json

# Imports from outside lean-v8: the pinned Aeneas backend and these modules of the pinned Lean toolchain's library.
ALLOWED_EXTERNAL = frozenset({"Aeneas", "Aeneas.Data.Discriminant", "Init.Data.Char.Lemmas", "Init.Data.List.Find", "Std",
                              "Init.Data.Nat.ToString", "Init.Data.String.Lemmas.Intercalate", "Std.Data.HashSet"})
ALLOWED_AXIOMS = frozenset({"propext", "Classical.choice", "Quot.sound"})
REPORT = re.compile(r"'(?P<name>[^'\n]+)' (?:depends on axioms: \[(?P<axioms>[^\]]*)\]|(?P<none>does not depend on any axioms))\n")
CHECKER = "fang-v8-check"
LIBRARY = "FangV8"


def require(value, message):
    if not value:
        raise ValueError(message)


def digest(path):
    return sources.digest(path)


def imports(path):
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"(?:public )?import ([A-Za-z0-9_. ]+)", line)
        if match:
            result.extend(match[1].split())
        elif re.match(r"\s*(?:public\s+)?import\b", line):
            raise ValueError(f"Unreviewed import syntax in {path.name}")
    return result


def closure(project, modules, roots):
    order, visiting, external = [], set(), set()

    def visit(name):
        if name in order:
            return
        if name not in modules:
            external.add(name)
            return
        require(name not in visiting, "Import cycle at " + name)
        visiting.add(name)
        for dependency in imports(project / (name.replace(".", "/") + ".lean")):
            visit(dependency)
        visiting.remove(name)
        order.append(name)

    for root in roots:
        visit(root)
    return order, external


def check_closures(project, lean_map):
    """Check every executable closure, the library closure and the external imports; return the closure sizes.

    Each executable's import closure must equal its pinned closure, the library must be exactly the modules no
    executable roots, and every import from outside lean-v8 must be in ALLOWED_EXTERNAL.
    """
    modules = {relative[:-len(".lean")].replace("/", "."): relative
               for relative in lean_map["files"] if relative.endswith(".lean")}
    mains, external, sizes = set(), set(), {}
    for name, entry in sorted(lean_map["executables"].items()):
        order, outside = closure(project, modules, [entry["root"]])
        require(sorted(order) == sorted(entry["closure"]), name + " import closure differs from the pinned closure")
        mains.add(entry["root"])
        external |= outside
        sizes[name] = len(order)
    library_order, library_external = closure(project, modules, lean_map["library_roots"])
    require(set(library_order) == set(modules) - mains, "Library closure is not exactly the pinned module set")
    external |= library_external
    unpinned = sorted(external - ALLOWED_EXTERNAL)
    require(not unpinned, "Unpinned external import: " + ", ".join(unpinned))
    sizes.update(library=len(library_order), external=sorted(external))
    return sizes


def audit_text(roots, names):
    lines = ["-- Fixed axiom audit generated by tools/build-v8-lean.py from lean-v8/audits.json."]
    lines += [f"import {root}" for root in roots]
    lines += [""] + [f"#print axioms {name}" for name in names]
    return "\n".join(lines) + "\n"


def parse_audit(text, names, recorded):
    require("sorryAx" not in text, "Audit output mentions sorryAx")
    reports, end = {}, 0
    for match in REPORT.finditer(text):
        require(text[end:match.start()] == "", "Unexpected audit output")
        end = match.end()
        name = match["name"]
        require(name not in reports, "Duplicate audit report: " + name)
        axioms = [] if match["none"] else sorted(item.strip() for item in match["axioms"].split(","))
        require(set(axioms) <= ALLOWED_AXIOMS, f"Nonstandard axiom in {name}: {axioms}")
        reports[name] = axioms
    require(text[end:] == "", "Unexpected trailing audit output")
    require(sorted(reports) == sorted(names), "Audit reports differ from the fixed audit list")
    for name in names:
        require(reports[name] == sorted(recorded[name]), "Axioms differ from the gate record: " + name)
    return reports


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="fresh build directory (ext4 recommended)")
    parser.add_argument("--lean-toolchain", type=Path, required=True, help="pinned Lean 4.35.0 toolchain root")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--backend", type=Path, help="pinned local Aeneas backend to copy (read only)")
    source.add_argument("--packages", type=Path, help="Lake package directory from tools/fetch-v8-backend.py")
    parser.add_argument("--aeneas-checkout", type=Path, help="local Aeneas Git checkout, required with --backend")
    parser.add_argument("--receipts", action="store_true", help="also check the source map against evidence/ receipts")
    parser.add_argument("--memory-mib", type=int, default=5120)
    parser.add_argument("--wall-seconds", type=int, default=5400)
    args = parser.parse_args(argv)
    require(sys.platform == "linux", "Lean builds require Linux or WSL")
    require(args.backend is None or args.aeneas_checkout is not None, "--backend needs --aeneas-checkout")
    out = args.out.resolve()
    out.mkdir(mode=0o700, exist_ok=False)
    toolchain = args.lean_toolchain.resolve()
    lake = toolchain / "bin/lake"
    report = {"schema": "fang-v8-lean-build-v1", "status": "running",
              "started_utc": datetime.now(timezone.utc).isoformat(),
              "scope": "Lake build of lean-v8 (the lexer-gate and document-gate modules, Fang.BoundedInput and the "
                       "checker and exporter mains) and the fixed axiom audits of every gate. Compiled execution of "
                       "fang-v8-check and fang-v8-tstp trusts the Lean compiler, runtime and OS; per-input acceptance "
                       "and export are separate runtime matters."}
    supervisor = Supervisor(Limits(wall_seconds=args.wall_seconds, memory_mib=args.memory_mib,
                                   log_bytes=64 << 20, artifact_bytes=64 << 30))
    report["limits"] = {"wall_seconds": args.wall_seconds, "sampled_tree_rss_mib": args.memory_mib}
    try:
        check = supervisor.check
        lean_map = sources.load_map(ROOT, sources.LEAN_MAP, sources.LEAN_SCHEMA, check)
        listed = sources.lean_files(ROOT, check)
        report["source_map_sha256"] = digest(ROOT / sources.LEAN_MAP)
        report["sources_checked"] = len(listed)
        if args.receipts:
            report["receipt_entries_checked"] = sources.check_lean_receipts(ROOT, check)
        project_source = ROOT / lean_map["project"]
        executables = lean_map["executables"]
        report["closures"] = check_closures(project_source, lean_map)
        pins = v8_backend.load_pins(ROOT)
        report["backend_pins_sha256"] = digest(ROOT / v8_backend.PINS)
        project = out / "project"
        for relative in lean_map["files"]:
            target = project / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(project_source / relative, target)
            require(digest(target) == lean_map["files"][relative]["sha256"], "Copied project file differs: " + relative)
        packages = project / ".lake/packages"
        packages.mkdir(parents=True)
        commands = []

        def plain(command, cwd=None):
            check()
            done = subprocess.run(list(map(str, command)), cwd=cwd, capture_output=True, timeout=1800,
                                  env={"PATH": "/usr/bin:/bin", "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8",
                                       "GIT_ALLOW_PROTOCOL": "file", "HOME": str(out)})
            commands.append({"command": list(map(str, command)), "exit_code": done.returncode,
                             "stderr": done.stderr.decode("utf-8", "replace")[-2000:]})
            require(done.returncode == 0, "Setup command failed: " + " ".join(map(str, command)))
            return done.stdout.decode("utf-8", "replace")

        if args.backend is not None:
            backend = args.backend.resolve()
            report["backend"] = {"mode": "local-copy", "path": str(backend), "aeneas_checkout": str(args.aeneas_checkout)}
            aeneas = packages / "aeneas"
            plain(["git", "clone", "-q", "--no-checkout", args.aeneas_checkout.resolve(), aeneas])
            plain(["git", "-C", aeneas, "-c", "advice.detachedHead=false", "checkout", "-q", pins["packages"]["aeneas"]["rev"]])
            plain(["git", "-C", aeneas, "remote", "set-url", "origin", lean_map["aeneas"]["url"]])
            (aeneas / v8_backend.AENEAS_SUBDIR / ".lake").mkdir(parents=True)
            plain(["cp", "-a", backend / ".lake/build", aeneas / v8_backend.AENEAS_SUBDIR / ".lake/build"])
            for name in sorted(pins["packages"]):
                if name != "aeneas":
                    plain(["cp", "-a", backend / ".lake/packages" / name, packages / name])
        else:
            report["backend"] = {"mode": "fetched", "path": str(args.packages.resolve())}
            for name in sorted(pins["packages"]):
                plain(["cp", "-a", args.packages.resolve() / name, packages / name])
        for name, pin in sorted(pins["packages"].items()):
            rev = plain(["git", "-C", packages / name, "rev-parse", "HEAD"]).strip()
            require(rev == pin["rev"], f"Package {name} is not at its pinned revision")
        report["setup_commands"] = commands
        # A fetched tree may differ from the pinned backend only in Lake build records; a local copy may not differ.
        report["pin_check"] = "fetch" if args.packages is not None else "exact"
        before_result, before_rows, problems = v8_backend.check_packages(packages, pins, check,
                                                                         fetch=args.packages is not None)
        report["packages_before"] = before_result
        require(not problems, "Backend packages differ from their pins: " + ", ".join(problems))
        gitbin = out / "gitbin"
        gitbin.mkdir()
        (gitbin / "git").symlink_to("/usr/bin/git")
        (out / "home").mkdir()
        (out / "tmp").mkdir()
        environment = {"PATH": f"{toolchain / 'bin'}:{gitbin}", "HOME": str(out / "home"), "TMPDIR": str(out / "tmp"),
                       "LEAN_NUM_THREADS": "1", "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"}
        report["environment"] = environment
        report["toolchain"] = {"path": str(toolchain), "lean_sha256": digest(toolchain / "bin/lean"),
                               "lake_sha256": digest(lake)}
        stages = out / "stages"
        stages.mkdir()

        def run(label, command, *, stdout_limit=None):
            wrapped = ["/usr/bin/env", "GIT_ALLOW_PROTOCOL=file", *map(str, command)]
            record, stdout, stderr = supervisor.run(label, wrapped, stages / label, stages, environment=environment,
                                                    stdout_limit=stdout_limit)
            require(record["classification"] == "completed" and record["exit_code"] == 0, "Stage failed: " + label)
            return stdout.decode("utf-8", "replace"), stderr.decode("utf-8", "replace")

        run("lake-build", [lake, "-d", project, "--no-cache", "build", LIBRARY, *sorted(executables)])
        for relative, entry in lean_map["files"].items():
            require(digest(project / relative) == entry["sha256"], "Project source changed during the build: " + relative)
        after_result, _, problems = v8_backend.check_packages(packages, pins, check, allow_additions=True,
                                                              before=before_rows)
        report["packages_after"] = after_result
        require(not problems, "Build changed pinned backend content: " + ", ".join(problems))
        audits = json.loads((project / "audits.json").read_text(encoding="utf-8"))
        require(audits.get("schema") == "fang-v8-audits-v2", "Unexpected audit list")
        # audits.json records each gate's axioms; with --receipts it was also checked against the gate receipts.
        recorded = {name: row["axioms"] for name, row in audits["names"].items()}
        (out / "audit").mkdir()
        reports = {}
        for index, (gate, roots) in enumerate(sorted(audits["roots"].items())):
            names = sorted(name for name, row in audits["names"].items() if row["gate"] == gate)
            audit_file = out / "audit" / f"Audit{index}.lean"
            audit_file.write_text(audit_text(roots, names), encoding="utf-8")
            stdout, stderr = run(f"axiom-audit-{index}", [lake, "-d", project, "env", "lean", audit_file])
            require(stderr == "", "Axiom audit wrote diagnostics")
            reports.update(parse_audit(stdout, names, recorded))
        require(sorted(reports) == sorted(audits["names"]), "Audit reports differ from the fixed audit list")
        report["axiom_audits"] = {"count": len(reports), "gates": sorted(audits["roots"]),
                                  "compared_with_gate_record": True, "gate_record_checked_against_receipts": args.receipts,
                                  "axioms": sorted({axiom for value in reports.values() for axiom in value})}
        bin_dir = out / "bin"
        bin_dir.mkdir()
        built = {}
        for name, entry in sorted(executables.items()):
            binary = project / ".lake/build/bin" / name
            shutil.copy2(binary, bin_dir / name)
            require(digest(bin_dir / name) == digest(binary), "Copied executable differs: " + name)
            usage_record, usage_out, usage_err = supervisor.run("usage-" + name, [bin_dir / name], stages / ("usage-" + name),
                                                                stages, environment={"PATH": "/usr/bin:/bin", "LANG": "C.UTF-8",
                                                                                     "LC_ALL": "C.UTF-8"})
            require(usage_record["exit_code"] == 64 and usage_out == b""
                    and usage_err == (entry["usage"] + "\n").encode(), "Usage contract differs: " + name)
            built[name] = {"path": str(bin_dir / name), "sha256": digest(bin_dir / name),
                           "bytes": (bin_dir / name).stat().st_size}
        require(digest(toolchain / "bin/lean") == report["toolchain"]["lean_sha256"]
                and digest(lake) == report["toolchain"]["lake_sha256"], "Lean toolchain changed during the build")
        report.update(status="built-and-audited", executables=built, executable=built[CHECKER]["path"],
                      executable_sha256=built[CHECKER]["sha256"], executable_bytes=built[CHECKER]["bytes"])
    except BaseException as error:
        report.update(status="failed", error=f"{type(error).__name__}: {error}")
    finally:
        report["stages"] = supervisor.records
        report["sampled_peak_rss_kib"] = supervisor.peak_kib
        report["finished_utc"] = datetime.now(timezone.utc).isoformat()
        supervisor.close()
        write_json(out / "manifest.json", report)
    print(json.dumps({key: report.get(key) for key in ("status", "executable_sha256", "error")}))
    return int(report["status"] != "built-and-audited")


if __name__ == "__main__":
    raise SystemExit(main())
